// REUSABLE KERNEL VISUAL COMPONENTS.
//
// -------------------------------------------------------------------------
// WHY THIS EXISTS
// -------------------------------------------------------------------------
// tab5_botao() was written, byte for byte identical, in FOUR different files
// of this system (arquivos, azimutal, config, mesh - the mesh one was
// called "caixa") before it became this. The comment each copy
// carried told the same story: "getTextStyle()/setTextStyle() stops
// the middle_center datum leaking to whoever draws next - the SAME
// gotcha that already bit tab5_power_mostrar". Four different apps
// had to rediscover the same bug, each with its own local patch.
//
// That is exactly the kind of thing a new app should NOT have to
// learn on its own. If you are writing a button, use tab5_botao(); if
// it ever has a bug, the fix applies to every app at once, instead of
// having to remember to visit each copy.
//
// See docs/ESCREVENDO_APPS.md for the rest of the contract.
#pragma once

#include <M5Unified.h>
#include "tab5_tema.hpp"

// The area's current background colour (kernel/app.h): the default text background.
uint16_t sistema_cor_fundo(void);

// FONT HISTORY: Font0 -> Font4 -> DejaVu24 -> FreeSans12pt7b (13 to
// all 1-bit bitmaps scaled by a fraction) -> smoothed Roboto at
// native heights (below). The title is FreeMonoBold12pt7b since
// wherever it appears (status bar, home, app section).

// -------------------------------------------------------------------------
// SMOOTH FONTS - the end of jagged letters
// -------------------------------------------------------------------------
// Until now ALL body text was FreeSans12pt7b (1-bit bitmap, 29 px)
// multiplied by a fraction - tab5_fonte_tam(3.2) = 0.88x, (2.3) = 0.63x.
// Fractional bitmap scaling duplicates some pixel rows and drops
// others: the typing bar (0.88x) came out visibly worse than the message
// bubble (1.05x, almost native).
//
// Now the body is Roboto (Apache 2.0) SMOOTHED - 8-bit antialiasing,
// VLW format - generated by gerar_fontes.py at ~20 NATIVE heights (12 to 56
// px), regular and bold, with Portuguese accents. tab5_texto() picks the
// native height closest to what was asked for: it never scales again.
//
//   tab5_fonte_corpo(d);          // or tab5_fonte_corpo_negrito(d)
//   tab5_texto(d, 3.2f);          // the SAME number as before (N -> N*8 px)
//
// TITLE is still FreeMonoBold12pt7b (tab5_fonte_titulo) - monospaced on
// purpose - and so is Font0 for fixed-column tables.
void tab5_fontes_iniciar(void);                     // at boot, before the 1st draw
const lgfx::IFont* tab5_fonte_suave(bool negrito, int altura_px);

// The default body font (the height of the old FreeSans12: 29 px -> 28).
#define TAB5_FONTE_CORPO         (tab5_fonte_suave(false, 29))
#define TAB5_FONTE_CORPO_ALT_PX  29   // the "old style" reference height (N*8/29)

// The "old style" size - only for code that still scales a font that is NOT
// the body font (the title). For the body, use tab5_texto().
inline float tab5_fonte_tam(float tamanho_estilo_antigo) {
  return tamanho_estilo_antigo * (8.0f / TAB5_FONTE_CORPO_ALT_PX);
}

// Sets text to size N (height N*8 px) in the family in use: with
// the body or bold font, switches to the closest NATIVE height (text size
// 1); with another font (title, Font0), scales as before.
void tab5_texto(lgfx::LovyanGFX& d, float tamanho_estilo_antigo);

// Family switch. setFont() is GLOBAL display STATE, not part of
// TextStyle/getTextStyle() - whoever switches promises to switch back:
//
//   tab5_fonte_titulo(d);
//   d.drawString("MESH", cx, cy);
//   tab5_fonte_corpo(d);
inline void tab5_fonte_titulo(lgfx::LovyanGFX& d) { d.setFont(&fonts::FreeMonoBold12pt7b); }

// SMOOTH TITLE - the SYSTEM title. Roboto bold at the requested native
// height (px), no scaling: the partner of the smooth body, with accents. The
// tab5_fonte_titulo() above (monospaced, 1-bit) was kept only for the game (the
// app_cobra folder is not touched - it is ITS way).
#define TAB5_TITULO_PX 36     // section/page title
void tab5_titulo(lgfx::LovyanGFX& d, int altura_px = TAB5_TITULO_PX);
void tab5_fonte_corpo(lgfx::LovyanGFX& d);
void tab5_fonte_corpo_negrito(lgfx::LovyanGFX& d);

// NAMED BUTTON TEXT SIZES (so as not to configure each button,
// scattered around the programs, individually).
//
// THE PROBLEM THIS SOLVES: before this change, each app that wanted a
// "big" button wrote the number by hand (4.0f, or a sum like 2.0f*2)
// right at the call site - scattered across Azimutal, Arquivos, Mesh...
// In a single session, two buttons were left out of a "general" increase just
// because their call was not found in the manual sweep. With a NAME
// instead of the raw number, changing how big "big" is changes here ONCE and applies to
// every app that uses the name - and the name itself, in the middle of the code, is an
// easy clue to find with a search (grep) next time.
//
// IT IS NOT A GLOBAL MULTIPLIER ON PURPOSE: this system's buttons do not
// all want the SAME increase (Settings' went up 20%, Azimutal's 100%) -
// a single factor applied on top of each caller's tamanho_texto
// would solve "increase everything by X%" but not "this dozen specific buttons
// needs to be big". The NAMES cover the real case: few categories
// (default/big), reused where they make sense.
#define TAB5_BOTAO_TEXTO_PADRAO  2.0f   // the system's ordinary button, no special request
#define TAB5_BOTAO_TEXTO_GRANDE  4.0f   // +100% of the default, used in several apps

// CHART GRID - IN A SINGLE PLACE (Power and Tasks use the same one).
// Born in app_energia.cpp,
// hand-picked (it is not TFT_DARKGREY: LovyanGFX's mid grey, 0x7BEF,
// would compete with the chart line - the grid is only a reading reference,
// the eye finds it when looking for it and ignores it when looking at the data). It went up twice:
// (26,26,32) -> (44,44,54) (it vanished in the panel's dark) ->
// (64,64,78). A single value, both charts (Power and Tasks) follow
// together next time it changes.
#define TAB5_GRAFICO_COR_GRADE  TEMA_LINHA   // the theme's divider

// Filled rounded rectangle with centred text - this system's default
// "button". Saves and restores the text style by itself.
//
//   tab5_botao(d, x, y, largura, altura, "OK", TFT_SKYBLUE);
//   tab5_botao(d, x, y, largura, altura, "OK", TFT_SKYBLUE, TFT_WHITE, TAB5_BOTAO_TEXTO_GRANDE);
//
// tamanho_texto is FLOAT (it was int) - a request to enlarge the
// button label by 20% in one app (Settings) and 100% in another (Azimutal) needs
// a fraction; callers with an integer literal (2, 3...) still compile
// identically, and simply gain the option not to round for those who need it.
void tab5_botao(lgfx::LovyanGFX& d, int x, int y, int l, int a,
               const char* txt, uint16_t fundo,
               uint16_t tinta = TFT_BLACK, float tamanho_texto = TAB5_BOTAO_TEXTO_PADRAO);

// MONOSPACED WITH ACCENTS. FreeMono12pt7b (Terminal, code editor) only
// has ASCII: "ã" came out as a box. Here ASCII goes in mono and the rest (accent,
// symbol) in the body font, centred in the same cell - the grid does not change.
// Draws up to 'cols' characters (code points) starting at 'x' with the baseline
// at 'y_base' and returns where it stopped (to wrap the line). Colour: the current one.
const char* tab5_mono(lgfx::LovyanGFX& d, const char* t, int x, int y_base, int cw, int cols);

// Human-readable size: "512 B", "3.4 KB", "12.0 MB", "1.9 GB". One for every
// app and for the console (before, each had its own, each a different way).
void tab5_bytes_txt(char* out, size_t n, uint64_t bytes);

// Panel cell: small label on top, large value below, optional subtext
// underneath - the same design used on the home screen
// (shell.cpp, "GROVE"/"CARTAO") and in Azimutal's position panel. Using
// this instead of inventing another makes the new app read as part of the same
// system, not as a separate widget.
//
// 'cx' is the horizontal CENTRE of the cell: with two or more side by side, each
// gets the centre of its slice and the text centres itself.
void tab5_celula(lgfx::LovyanGFX& d, int cx, int y0,
                 const char* rotulo, const char* valor, uint16_t cor_valor,
                 const char* subtexto = nullptr);

// THICK SMOOTH LINE THAT RESPECTS THE CLIP. Use instead of M5GFX's drawWideLine /
// drawWedgeLine / drawSpot: those REPLACE the caller's clip
// with the line's own box and, at the end, CLEAR the clip (clearClipRect).
// Inside a scrolling list that unleashes everything that comes after - the rest of the
// item and the following items - and whatever goes past the window is left as a trail
// over the header and footer. Here the drawing is the same (edge smoothed
// by the distance to the segment, round cap), except each pixel goes through the
// clip in force and the clip is not touched. 'r' is the radius (half thickness).
void tab5_linha_grossa(lgfx::LovyanGFX& d, float x0, float y0, float x1, float y1,
                       float r, uint16_t cor);

// IS THE POINT (x, y) IN THE RECTANGLE (rx, ry, rl, ra)? The touch test of
// every button - it had been rewritten in each app.
inline bool tab5_dentro(int x, int y, int rx, int ry, int rl, int ra)
{
  return x >= rx && x < rx + rl && y >= ry && y < ry + ra;
}

// CUTS THE TEXT UNTIL IT FITS in 'max_l' px, in the font active on 'd'
// - by UTF-8 CHARACTER, never in the middle of one (in Portuguese almost all text
// has accents: "ã" is two bytes, and cutting between them draws garbage). Measures by
// binary search (log n measurements, not one per character removed). Returns the
// size left, in bytes. It was the same loop copied into a dozen
// places - and three of the copies cut by byte.
size_t tab5_cortar_ao_caber(lgfx::LovyanGFX& d, char* t, int max_l);
// The same, ending in "..." when it cut ('tam' = buffer size).
size_t tab5_cortar_com_reticencias(lgfx::LovyanGFX& d, char* t, size_t tam, int max_l);

// TEXT AT AN EXACT FONT HEIGHT (the smooth font of 'px'), cut with "..."
// at 'max_l' px (0 = no cut). Restores the body font and top_left at the end:
// whoever draws next inherits nothing.
// DURATION for display: "45 s", "12 min", "2 h 05 min" (in the current language).
void tab5_duracao(uint32_t segundos, char* out, size_t n);

void tab5_escrever(lgfx::LovyanGFX& d, const char* t, int x, int y, int px, bool negrito,
                   uint16_t cor, uint16_t fundo = sistema_cor_fundo(), uint8_t datum = top_left, int max_l = 0);

// SPRITE (M5Canvas) ALWAYS IN PSRAM. Use instead of new M5Canvas +
// createSprite: without setPsram(true) M5GFX asks for MALLOC_CAP_DMA, and on the P4
// PSRAM does NOT have that flag - the sprite lands in internal SRAM (272x272 at 16 bits
// takes ~148 KB, half the internal heap). And even with setPsram(true), if
// PSRAM fails M5GFX silently tries internal memory again. Here neither:
// either the buffer is in PSRAM, or nullptr comes back and the app carries on without the sprite.
//
// It starts as RGB565 (the panel format) and with the body font - a sprite has
// its own text state, separate from the display.
//
//   s_fundo = tab5_sprite_novo(&d, l, a);   // nullptr: out of memory
//   tab5_sprite_soltar(&s_fundo);           // frees and nulls the pointer
M5Canvas* tab5_sprite_novo(lgfx::LovyanGFX* pai, int largura, int altura);
void      tab5_sprite_soltar(M5Canvas** sprite);
