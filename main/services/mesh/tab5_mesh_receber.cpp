// ---------------------------------------------------------------------------
// Interpreting the messages we care about
// ---------------------------------------------------------------------------
// DeviceMetrics: 1=battery 2=voltage 3=channel_util 4=airtime 5=uptime
//
// 'nosso' (ours) tells OUR node's telemetry apart from telemetry arriving from the mesh.
// Without that distinction (that was the bug) any neighbouring node overwrote
// our health: "uptime 1136229s" appeared - 13 days - on a C6L that had
// restarted 35 times. Battery and voltage ALWAYS go to the node that owns the metric;
// only the health indicators are exclusive to ours.
static void ler_metrics(pb_leitor_t l, mesh_no_t* no, bool nosso)
{
  int n, t;
  while (pb_proximo_campo(&l, &n, &t)) {
    if      (n == 1 && t == 0) { uint64_t v = 0; pb_varint(&l, &v); if (no) no->bateria = (uint8_t)v; }
    else if (n == 2 && t == 5) { float f = 0; pb_float(&l, &f); if (no) no->tensao = f; }
    else if (n == 3 && t == 5) { float f = 0; pb_float(&l, &f); if (nosso) s_saude.uso_canal = f; }
    else if (n == 4 && t == 5) { float f = 0; pb_float(&l, &f); if (nosso) s_saude.airtime_tx = f; }
    else if (n == 5 && t == 0) { uint64_t v = 0; pb_varint(&l, &v); if (nosso) s_saude.uptime_s = (uint32_t)v; }
    else if (!pb_pular(&l, t)) { break; }
  }
  if (nosso) { s_saude.tem_metricas = true; }
}

// LocalStats - the mesh's health as seen by OUR node, and only by it.
//   1=uptime 2=channel_util 3=airtime 4..6=packet counters
//   7=nodes_online 8=nodes_total
// Newer versions add fields (noise floor, for example); pb_pular()
// takes care of them without us needing to know which they are.
static void ler_local_stats(pb_leitor_t l)
{
  int n, t;
  while (pb_proximo_campo(&l, &n, &t)) {
    if      (n == 1 && t == 0) { uint64_t v = 0; pb_varint(&l,&v); s_saude.uptime_s   = (uint32_t)v; }
    else if (n == 2 && t == 5) { float f = 0; pb_float(&l,&f);     s_saude.uso_canal  = f; }
    else if (n == 3 && t == 5) { float f = 0; pb_float(&l,&f);     s_saude.airtime_tx = f; }
    else if (n == 4 && t == 0) { uint64_t v = 0; pb_varint(&l,&v); s_saude.pkt_tx      = (uint32_t)v; }
    else if (n == 5 && t == 0) { uint64_t v = 0; pb_varint(&l,&v); s_saude.pkt_rx      = (uint32_t)v; }
    else if (n == 6 && t == 0) { uint64_t v = 0; pb_varint(&l,&v); s_saude.pkt_ruins   = (uint32_t)v; }
    else if (n == 7 && t == 0) { uint64_t v = 0; pb_varint(&l,&v); s_saude.nos_online = (uint16_t)v; }
    else if (n == 8 && t == 0) { uint64_t v = 0; pb_varint(&l,&v); s_saude.nos_total  = (uint16_t)v; }
    else if (n == 9 && t == 0) { uint64_t v = 0; pb_varint(&l,&v); s_saude.pkt_repetidos = (uint32_t)v; }
    else if (!pb_pular(&l, t)) { break; }
  }
  s_saude.tem_local = true;
  // NO LOG HERE. The
  // values already sit in s_saude, available on demand through the console's "mesh"
  // command (prints channel/airtime/uptime/nodes) whenever you need to look.
}

// HardwareModel (mesh.proto) - FULL TABLE, generated, no longer guessed.
//
// The previous version of this function was a switch with a dozen models
// picked by hand, on the argument that copying the whole official list
// "would age and lie". The argument didn't survive the first real
// use: a real mesh brought "model 110", "model 88",
// "model 81" - genuine nodes the guessed table simply didn't anticipate,
// among them 111 = M5Stack C6L, the very radio this system uses.
//
// The fix is not to guess more - it is to stop guessing. TAB5_MESH_HW_NOMES
// (tab5_mesh_hw_dados.cpp) is generated by gerar_hw.py straight from Meshtastic's
// official enum; "ages and lies" stops being a risk because re-exporting is
// a command, not a memory of which numbers exist.
const char* mesh_hw_nome(uint8_t hw)
{
  return TAB5_MESH_HW_NOMES[hw];   // hw is uint8_t: always inside the table
}

// User: 1=id 2=long_name 3=short_name 4=macaddr 5=hw_model
//
// 'id' and 'macaddr' were what was missing: the long and
// short names are LABELS that whoever renames on the phone changes at will, and from them
// there's no telling which DEVICE you are talking to. The id ("!a1b2c3d4") is
// derived from the MAC and stays with the radio forever.
static void ler_user(pb_leitor_t l, mesh_no_t* no)
{
  int n, t;
  while (pb_proximo_campo(&l, &n, &t)) {
    if      (n == 1 && t == 2) { pb_texto(&l, no->id,    sizeof(no->id)); }
    else if (n == 2 && t == 2) { pb_texto(&l, no->longo, sizeof(no->longo)); }
    else if (n == 3 && t == 2) { pb_texto(&l, no->curto, sizeof(no->curto)); }
    else if (n == 4 && t == 2) {
      // macaddr is 'bytes', not text - ler_texto can't be used (it
      // would end the string at the first 0x00 byte of the address).
      uint64_t k;
      if (!pb_varint(&l, &k)) { break; }
      if (k > pb_restam(&l)) { break; }
      if (k == 6) { memcpy(no->mac, l.p, 6); no->tem_mac = true; }
      l.p += (size_t)k;
    }
    else if (n == 5 && t == 0) { uint64_t v = 0; pb_varint(&l,&v); no->hw = (uint8_t)v; }
    else if (!pb_pular(&l, t)) { break; }
  }
}

// Position: 1=lat_i 2=lon_i (sfixed32)
static void ler_position(pb_leitor_t l, mesh_no_t* no)
{
  int n, t;
  while (pb_proximo_campo(&l, &n, &t)) {
    if      (n == 1 && t == 5) { uint32_t v = 0; if (!pb_fixo32(&l, &v)) { break; } no->lat_i = (int32_t)v; no->tem_pos = true; }
    else if (n == 2 && t == 5) { uint32_t v = 0; if (!pb_fixo32(&l, &v)) { break; } no->lon_i = (int32_t)v; }
    else if (!pb_pular(&l, t)) { break; }
  }
}

// NodeInfo: 1=num 2=user 3=position 4=snr 5=last_heard 6=device_metrics 9=hops
static void ler_node_info(pb_leitor_t l)
{
  bool fav_radio = false;   // is_favorite: proto3, absent = false
  uint32_t num = 0;
  mesh_no_t* no = nullptr;
  int n, t;
  while (pb_proximo_campo(&l, &n, &t)) {
    if (n == 1 && t == 0) {
      uint64_t v = 0; pb_varint(&l, &v); num = (uint32_t)v;
      no = achar_no(num);
      if (!no) { return; }
    }
    else if (!no) { if (!pb_pular(&l, t)) { break; } }         // num always comes first
    else if (n == 2 && t == 2) {
      pb_leitor_t s;
      if (pb_sub(&l,&s)) {
        // OUR node's User, raw: set_owner resends it whole (tab5_mesh_admin).
        if (num == s_meu_num && s_meu_num) { mesh_admin_guardar_user(s.p, (size_t)(s.fim - s.p)); }
        ler_user(s, no);
      }
    }
    else if (n == 3 && t == 2) { pb_leitor_t s; if (pb_sub(&l,&s)) ler_position(s, no); }
    else if (n == 4 && t == 5) { pb_float(&l, &no->snr); }
    else if (n == 5 && t == 5) { pb_fixo32(&l, &no->visto_em); marcar_epoch(no->visto_em); }
    else if (n == 6 && t == 2) { pb_leitor_t s; if (pb_sub(&l,&s)) ler_metrics(s, no, num == s_meu_num); }
    // via_mqtt: the node arrived over the INTERNET, not the radio. It changes the meaning
    // of everything seen about it - the SNR isn't its own, and it can't be reached over
    // RF. It deserves to show in the list.
    else if (n == 8 && t == 0) { uint64_t v = 0; pb_varint(&l,&v); no->via_mqtt = (v != 0); }
    else if (n == 9 && t == 0) { uint64_t v = 0; pb_varint(&l,&v); no->saltos = (uint8_t)v; }
    else if (n == 10 && t == 0) { uint64_t v = 0; pb_varint(&l,&v); fav_radio = (v != 0); }
    else if (!pb_pular(&l, t)) { break; }
  }

  // Keeps the label for when the radio isn't here. Renaming in the
  // phone app arrives by this same path, with the SAME num - and the
  // cache updates itself, without becoming a new contact.
  //
  // BOTH NOW, short AND long - only a usable short name used to get in
  // here (it was the only one tab5_mesh_nome_exibicao() promises to show). But the
  // node table (montar_linha(), app_mesh.cpp) always showed the long one
  // too, and ONLY from the live entry - with no cache, it stayed "(no name)" until
  // THIS SESSION saw a NodeInfo from that node again, which is rare (most
  // nodes are learnt from telemetry/position/text, never from NodeInfo).
  // See the big notice next to tab5_mesh_nome_longo_cache() in the .hpp.
  if (no) {
    lembrar_nome(num, curto_utilizavel(no->curto) ? no->curto : nullptr,
                       no->longo[0] ? no->longo : nullptr);
    fixar_se_pelo_ar(no);
    fav_do_radio(num, fav_radio);
    ++s_nos_ver;
  }
  sistema_avisar(AVISO_MESH_NOS);
}

// RING OF IDS ALREADY SEEN - its OWN dedup, separate from s_msgs.
//
// Until now, echo detection looked inside s_msgs[MESH_MAX_MSGS] - and
// MESH_MAX_MSGS is 8. It was born for the simple case (you send, the radio returns
// the same packet seconds later) and in that case 8 was always enough: it is unlikely
// that 8 messages from OTHER people arrive between the send and the echo.
//
// WITH MQTT THAT CHANGES. The same packet can arrive TWICE by paths with
// very different delays - one copy over local LoRa, another via the MQTT broker
// (another node's uplink, or our own downlink coming back) - and the delay between the
// two is no longer "a few predictable seconds", it is "however long the internet and the broker's
// queue take". In a mesh with an active bridge, traffic is also
// denser. The two together push the second copy OUTSIDE the window of
// 8 messages, and it gets in as if it were new - the same message
// twice in the conversation.
//
// The fix is a ring JUST FOR THIS, independent of what appears on screen: 256
// ids, 1 KB (in PSRAM, like the rest of the service's .bss), nothing but one
// uint32_t each. It was 64; with dense traffic going through the same ring, the
// window for a text shrank - the copy delayed by the bridge got in
// again. Stores no content - only "this id has already been through here".
#define MESH_DEDUP_N 256
static uint32_t s_ids_vistos[MESH_DEDUP_N];
static int      s_prox_id_visto = 0;

static bool id_ja_visto(uint32_t id)
{
  if (id == 0) { return false; }   // 0 is "no id" (see the id in tab5_mesh_enviar) - never dedup
  for (int i = 0; i < MESH_DEDUP_N; ++i) {
    if (s_ids_vistos[i] == id) { return true; }
  }
  return false;
}

static void marcar_id_visto(uint32_t id)
{
  if (id == 0) { return; }
  s_ids_vistos[s_prox_id_visto] = id;
  s_prox_id_visto = (s_prox_id_visto + 1) % MESH_DEDUP_N;
}

void guardar_msg(uint32_t de, uint32_t para, uint8_t canal, const char* txt,
                        uint32_t quando, float snr, int32_t rssi, uint32_t id,
                        bool via_mqtt, uint8_t saltos)
{
  // ECHO OF OUR OWN MESSAGE, AND DUPLICATE VIA MQTT BRIDGE: both are discarded
  // by the same id, see the ring comment just above.
  //
  // When sending, we store the message here straight away. Seconds later the radio
  // RETURNS the same packet as received (from = our number) - and before
  // we read field 6 of the MeshPacket it arrived with id 0, became a SECOND
  // copy, and that copy was what the screen showed. No id, no delivery mark:
  // that is why the green tick and the red triangle never appeared on
  // sent messages.
  //
  // The packet id is the same one we sent, so it identifies the echo without
  // ambiguity. It also works for a message sent from the PHONE through the
  // C6L: it arrives only once, with the id the radio gave it.
  if (id_ja_visto(id)) { return; }
  marcar_id_visto(id);

  // Pushes the old ones to the end: index 0 is always the most recent, which is
  // how the screen wants to read it.
  if (s_n_msgs < MESH_MAX_MSGS) { s_n_msgs++; }
  for (int i = s_n_msgs - 1; i > 0; --i) { s_msgs[i] = s_msgs[i-1]; }
  memset(&s_msgs[0], 0, sizeof(s_msgs[0]));
  s_msgs[0].de = de;
  s_msgs[0].para = para;
  s_msgs[0].canal = canal;
  // 0xFFFFFFFF is Meshtastic's broadcast address. Any other value
  // equal to our number means a message addressed TO YOU.
  s_msgs[0].direta = (para != 0xFFFFFFFFu) && (para == s_meu_num);
  snprintf(s_msgs[0].texto, sizeof(s_msgs[0].texto), "%s", txt);
  s_msgs[0].quando = quando;
  s_msgs[0].snr = snr;
  s_msgs[0].rssi = rssi;
  s_msgs[0].via_mqtt = via_mqtt;
  s_msgs[0].saltos = saltos;
  s_msgs[0].id = id;

  // OUR OWN MESSAGE IS NOT "UNREAD". Seems obvious and wasn't: the counter went up
  // for everything, and tab5_mesh_enviar corrected it AFTERWARDS by decrementing s_nao_lidas -
  // but forgot the CONVERSATION's counter. Result: sending on LongFast left
  // a "1" on the conversation you were looking at.
  //
  // The decision has to live here, where we know whose message it is, and not
  // in a patch on the sender's side.
  const bool minha = (de == s_meu_num);

  // ALSO TRACKS WHAT LEFT FROM THE PHONE.
  //
  // Until now only what the Tab5 sent went into the ring - so a message sent
  // from the phone app through the C6L appeared in the conversation WITHOUT any mark,
  // and you were left not knowing whether it arrived.
  //
  // But its ACK DOES REACH US: the C6L relays all FromRadio traffic
  // to every connected client, and we are one. We only discarded it for
  // not having the id in the table. Registering it here, the same Routing that marks
  // ours now marks the phone's too.
  //
  // The condition is "came from our node and has an id": that is the definition of "a message
  // this radio transmitted", whether this screen or the phone asked for it.
  //
  // LIVE TRAFFIC ONLY. During the dump the node may redeliver an old message of
  // ours: noted here it became SENDING and, 60 s later, "no reply" -
  // written to envios.txt OVER the real outcome it already had.
  if (minha && id != 0 && trafego_ao_vivo()) { anotar_envio(id, para); }

  // THE CONVERSATION IS ALWAYS "THE OTHER SIDE".
  //
  // A broadcast goes to the channel. A direct one goes to the OTHER node - which is the
  // sender when we receive, and the RECIPIENT when we are the ones
  // sending. Without that distinction, a direct message we sent landed in the
  // channel's conversation, because the "direct" test looked only at the recipient.
  const bool difusao = (para == 0xFFFFFFFFu);
  const uint32_t outro = (de == s_meu_num) ? para : de;
  const int ci = difusao ? achar_ou_criar_conversa(true, canal, 0)
                         : achar_ou_criar_conversa(false, 0, outro);
  if (ci >= 0) {
    if (!minha) { s_conv[ci].nao_lidas++; }
    s_conv[ci].ultima_em = quando;
    // Moves up to the top of the directs. A channel has a fixed place (by index).
    if (!difusao) { s_conv_seq[ci] = ++s_seq; ++s_conv_ver; }
    gravar_msg(ci, &s_msgs[0]);
  }

  // A real message (sent or received) is the return to talking that undoes
  // an earlier delete - see the big comment on the flag, above. IT APPLIES TO
  // BOTH (channels can be deleted now too): the line above already
  // recreates the channel's conversation unconditionally (and should - a real
  // message is itself the "it's back" signal), but WITHOUT clearing the flag here
  // it would stay written on the SD card and the channel would vanish on the next boot.
  if (difusao) { desmarcar_apagada(true, canal); }
  else         { desmarcar_apagada(false, outro); }

  // THE COUNTER ONLY GOES UP AFTER THE LINE IS IN THE WRITER (gravar_msg, above).
  // The screen reads this number without a lock: going up earlier, it could ask to reread
  // the SD card with the line not even handed over yet - and nothing else made it reread
  // afterwards. This NEVER saturates - see the big notice next to the declaration.
  ++s_total_msgs;

  publicar_notif();
  // THE ID GOES IN THE LOG: a repeated message that passes through here has already been through
  // the discard-by-id (id_ja_visto). With the id in view, you can tell at once whether
  // the repeat is from the NETWORK (new id - the sender or a bridge resent it) or
  // ours (same id - the discard failed). And the origin: radio or internet.
  ESP_LOGI(TAG, "message %s from %08lX (id %08lX, %s): %s",
           s_msgs[0].direta ? "DIRECT" : "on channel", (unsigned long)de, (unsigned long)id,
           via_mqtt ? "internet" : "radio", txt);

  sistema_avisar(AVISO_MESH_MSG);
}

// "THE NODES CHANGED" FOR THE SCREEN, at most 4 per second: the MQTT bridge arrives
// in bursts, and each notice made the nodes page and the column check themselves
// again. The table changes immediately; only the notice waits.
static void avisar_nos(void)
{
  static uint32_t ultimo_ms = 0;
  const uint32_t t = tab5_agora_ms();
  if (t - ultimo_ms < 250u) { return; }
  ultimo_ms = t;
  sistema_avisar(AVISO_MESH_NOS);
}

static void ler_data(pb_leitor_t l, uint32_t de, uint32_t para, uint8_t canal,
                     uint32_t quando, float snr, int32_t rssi, uint32_t id,
                     bool via_mqtt, uint8_t saltos, bool transp_mqtt)
{
  int porta = 0;
  uint32_t pedido = 0;                 // request_id: which of OUR packets this is about
  int bitfield = -1;                   // -1 = not present (firmware before 2.5)
  const uint8_t* pay = nullptr; size_t pay_n = 0;
  int n, t;
  while (pb_proximo_campo(&l, &n, &t)) {
    if      (n == 1 && t == 0) { uint64_t v = 0; pb_varint(&l,&v); porta = (int)v; }
    else if (n == 2 && t == 2) {
      uint64_t k; if (!pb_varint(&l,&k)) break;
      if (k > pb_restam(&l)) break;              // see pb_restam(): adding to the pointer overflows
      pay = l.p; pay_n = (size_t)k; l.p += (size_t)k;
    }
    else if (n == 6 && t == 5) { pb_fixo32(&l, &pedido); }   // request_id
    else if (n == 9 && t == 0) { uint64_t v = 0; pb_varint(&l,&v); bitfield = (int)v; }
    else if (!pb_pular(&l, t)) { break; }
  }
  // THE SENDER'S STAMP (bit 0 = OK_TO_MQTT, see MESH_CFG_OK_MQTT): without it,
  // a public server gateway doesn't take the message to MQTT. In the log, to
  // answer "why didn't so-and-so's message reach the server".
  if (porta == PORT_TEXTO && !via_mqtt && de != s_meu_num) {
    ESP_LOGI(TAG, "text from %08lX: OK for MQTT %s", (unsigned long)de,
             bitfield < 0 ? "absent (old firmware - public gateway discards)"
                          : (bitfield & 1) ? "yes" : "NO (public gateway discards)");
  }

  // THE ACKNOWLEDGEMENT HAS NO MANDATORY BODY.
  //
  // An ACK is a Routing with error_reason ABSENT - and an absent field in protobuf
  // takes no bytes at all, so the payload comes EMPTY. Testing "if (!pay) return"
  // before this point, as the code did, would discard precisely the success case
  // and only the error would appear on screen.
  if (porta == PORT_ROTEAMENTO) {
    if (pedido == 0) { return; }
    int erro = 0;
    if (pay) {
      pb_leitor_t rl = { pay, pay + pay_n };
      int rn, rt;
      while (pb_proximo_campo(&rl, &rn, &rt)) {
        if (rn == 3 && rt == 0) { uint64_t v = 0; pb_varint(&rl,&v); erro = (int)v; }
        else if (!pb_pular(&rl, rt)) { break; }
      }
    }
    marcar_envio(pedido, erro, de, transp_mqtt);
    return;
  }

  if (!pay) { return; }

  // A NODE'S INTRODUCTION, LIVE (NODEINFO_APP, payload = User).
  //
  // FromRadio.node_info only comes in the configuration DUMP - the node does NOT resend it
  // when a neighbour introduces itself later; it relays the PACKET, and the client
  // is the one that reads the User inside it. Without reading this port, every node that
  // appeared after the dump (and EVERY node in internet mode, which has no real
  // dump) stayed without a name, model or MAC until the radio's next
  // restart - and the conversation with it showed up under the hex id.
  if (porta == PORT_NODEINFO) {
    mesh_no_t* no = achar_no(de);
    if (de == s_meu_num && s_meu_num) { mesh_admin_guardar_user(pay, pay_n); }
    if (no) {
      ler_user(pb_leitor_t{ pay, pay + pay_n }, no);
      lembrar_nome(de, curto_utilizavel(no->curto) ? no->curto : nullptr,
                   no->longo[0] ? no->longo : nullptr);
      ++s_nos_ver;
      avisar_nos();
    }
    return;
  }

  // LIVE POSITION (POSITION_APP, payload = Position). Same reason: without
  // this a node's position was only the one from the dump, and aged forever.
  if (porta == PORT_POSICAO) {
    mesh_no_t* no = achar_no(de);
    if (no) { ler_position(pb_leitor_t{ pay, pay + pay_n }, no); }
    return;
  }

  if (porta == PORT_TEXTO) {
    char txt[MESH_TEXTO];
    size_t c = (pay_n < sizeof(txt) - 1) ? pay_n : sizeof(txt) - 1;
    memcpy(txt, pay, c); txt[c] = 0;
    // A LINE BREAK BECOMES A SPACE. The history on the SD card is one message per
    // line: a "\n" in the middle (common in what comes from the Telegram bridge) cut the
    // message there, and the rest became a line without "M4," that the reader skips.
    for (size_t k = 0; k < c; ++k) { if (txt[k] == '\n' || txt[k] == '\r' || txt[k] == '\t') { txt[k] = ' '; } }
    s_c_texto++;
    // NO LOG HERE. The
    // via_mqtt/hops of THIS packet (before any screen fallback) is
    // stored in s_msgs[0] as usual - "mesh" in the console can read
    // the most recent message with tab5_mesh_msg(0, ...) and see both fields
    // raw, on demand, without needing any automatic log.
    guardar_msg(de, para, canal, txt, quando, snr, rssi, id, via_mqtt, saltos);
  }
  else if (porta == PORT_TELEMETRIA) {
    // Telemetry: 2=device_metrics, 6=local_stats. The other variants
    // (environment, air quality, power) wait until there is a node with a
    // sensor - skipping is safe and costs nothing.
    s_c_telemetria++;
    pb_leitor_t tl = { pay, pay + pay_n };
    int tn, tt;
    while (pb_proximo_campo(&tl, &tn, &tt)) {
      s_ultima_variante = tn;    // which Telemetry variant came last
      // Field 1 = time: the time at which OUR node generated the telemetry.
      if      (tn == 1 && tt == 5) { uint32_t v = 0; pb_fixo32(&tl, &v); if (de == s_meu_num) { marcar_hora_viva(v); } }
      else if (tn == 2 && tt == 2) { pb_leitor_t s; if (pb_sub(&tl,&s)) ler_metrics(s, achar_no(de), de == s_meu_num); }
      // LocalStats only makes sense from our own node: it is ITS view of the mesh.
      else if (tn == 6 && tt == 2 && de == s_meu_num) { s_c_localstats++; pb_leitor_t s; if (pb_sub(&tl,&s)) ler_local_stats(s); }
      else if (!pb_pular(&tl, tt)) { break; }
    }
  }
}

// MeshPacket: 1=from 2=to 3=channel 4=decoded 6=id 7=rx_time 8=rx_snr
// 9=hop_limit 12=rx_rssi 13=via_mqtt (bool, varint) 14=hop_start - the last
// two read so the screen can tell a message heard over the air
// (with the hop count) from a message that came in through the MQTT bridge.
static void ler_packet(pb_leitor_t l)
{
  uint32_t de = 0, quando = 0, para = 0xFFFFFFFFu, id = 0;
  uint8_t canal = 0;
  float snr = 0; int32_t rssi = 0;
  bool via_mqtt = false;
  // hop_limit: how much of the hop budget was LEFT when the packet arrived
  // here. hop_start: the ORIGINAL budget the sender set - it travels
  // along, unchanged, packet by packet. The difference is how many repeaters it
  // went through. Zero in hop_start is protobuf's default value (field
  // absent) - old firmware doesn't send it, so the count is undefined.
  uint32_t hop_limit = 0, hop_start = 0;
  // transport_mechanism (21): how the packet entered the radio. Only MQTT (5)
  // matters here - see "O IMPLICITO DO MQTT" (MQTT's implicit case) in marcar_envio().
  bool transp_mqtt = false;
  pb_leitor_t dados = { nullptr, nullptr };
  int n, t;
  while (pb_proximo_campo(&l, &n, &t)) {
    if      (n == 1 && t == 5) { pb_fixo32(&l, &de); }
    else if (n == 2 && t == 5) { pb_fixo32(&l, &para); }
    else if (n == 3 && t == 0) { uint64_t v = 0; pb_varint(&l,&v); canal = (uint8_t)v; }
    else if (n == 6 && t == 5) { pb_fixo32(&l, &id); }       // packet id
    else if (n == 7 && t == 5) { pb_fixo32(&l, &quando); }
    else if (n == 8 && t == 5) { pb_float(&l, &snr); }
    else if (n == 9 && t == 0) { uint64_t v = 0; pb_varint(&l,&v); hop_limit = (uint32_t)v; }
    else if (n == 12 && t == 0){ uint64_t v = 0; pb_varint(&l,&v); rssi = (int32_t)v; }
    // FIELDS 14 AND 15, checked against mesh.pb.h in the C6L firmware:
    // via_mqtt = 14, hop_start = 15. Until now 13 and 14 were read
    // - 13 is 'delayed' (obsolete, always 0) and 14 was via_mqtt mistaken
    // for hop_start. Result: MQTT was never recognised from the packet and the
    // hop count came out wrong or "--" (hence the fallback via NodeInfo).
    else if (n == 14 && t == 0){ uint64_t v = 0; pb_varint(&l,&v); via_mqtt = (v != 0); }
    else if (n == 15 && t == 0){ uint64_t v = 0; pb_varint(&l,&v); hop_start = (uint32_t)v; }
    else if (n == 21 && t == 0){ uint64_t v = 0; pb_varint(&l,&v); transp_mqtt = (v == 5); }
    else if (n == 4 && t == 2) { if (!pb_sub(&l, &dados)) break; }
    else if (!pb_pular(&l, t)) { break; }
  }
  // ZERO MEANS "ME". Meshtastic uses from=0 on a locally generated packet -
  // it appears as "fr=0x00000000" in the radio's own log. Without translating that:
  //   - LocalStats was discarded (the filter required de == my number), and the
  //     node counters stayed at 0/0;
  //   - and a phantom node numbered 0 got into the table.
  if (de == 0) { de = s_meu_num; }

  // HOPS = hop_start - hop_limit, only when hop_start was filled in (>0).
  // hop_start == 0 is protobuf's factory default (field absent,
  // old firmware) - in that case the count is undefined, and the sentinel says
  // so instead of inventing a "0 hops" that would be a lie.
  uint8_t saltos = MESH_SALTOS_DESCONHECIDO;
  if (hop_start > 0 && hop_start >= hop_limit) {
    saltos = (uint8_t)(hop_start - hop_limit);
  }

  // Interpreted at the end because the metadata (who, when, with what signal) may
  // come AFTER the data block in the serialisation.
  if (dados.p) { ler_data(dados, de, para, canal, quando, snr, rssi, id, via_mqtt, saltos, transp_mqtt); }

  marcar_epoch(quando);
  marcar_hora_viva(quando);

  if (de != 0) {
    mesh_no_t* no = achar_no(de);
    if (no) {
      if (snr != 0) { no->snr = snr; }
      // HOPS/VIA_MQTT HERE TOO - the screen showed little more than the ID,
      // compared with the web client. Both numbers were already calculated UP THERE for EVERY
      // packet (see 'saltos'/'via_mqtt' at the start of this function) and already went
      // to the MESSAGE (ler_data) - they had just never been applied to the NODE.
      // The node table only learnt that column when a NodeInfo arrived
      // (field 9/8, ler_node_info() further up) - a rare packet (a burst in the
      // initial dump, then only now and again), while ANY
      // packet - message, telemetry, position - already carries hop_start/
      // hop_limit/via_mqtt on its own edge (MeshPacket). "Unknown"
      // stayed on its own until the next NodeInfo, even with dozens of other
      // packets from the same node passing through here before that.
      //
      // Only overwrites hops when THIS packet actually brought hop_start
      // (saltos != DESCONHECIDO) - a packet without that info must not erase
      // a good value another packet had already taught. via_mqtt is always the
      // MOST RECENT path (a node can be heard directly at one moment and via
      // a bridge at another), so it overwrites without a guard.
      if (saltos != MESH_SALTOS_DESCONHECIDO) { no->saltos = saltos; }
      no->via_mqtt = via_mqtt;
      // LIVE SIGHTING. Marked here and not in ler_node_info on purpose:
      // node_info arrives in a burst in the configuration dump, for ALL nodes
      // at once, and stamping them all there would make the whole mesh seem to have been
      // heard just now. A packet is different - it only arrives when the node spoke.
      no->visto_local_ms = tab5_agora_ms();
      if (quando >= EPOCH_MINIMO) { no->visto_em = quando; }
      fixar_se_pelo_ar(no);   // heard over the air just now: gets the place at the top and protection from eviction
      ++s_nos_ver;
    }
  }
  avisar_nos();
}

// LocalStats comes as telemetry from our own node: 1=uptime 2=util 3=airtime
// 4..=counts, 8=nodes_online, 9=nodes_total, 10=noise_floor (varies with the version;
// we skip what we don't recognise).
void ler_from_radio(const uint8_t* buf, size_t n)
{
  pb_leitor_t l = { buf, buf + n };
  int f, t;

  // A LOOP, and not a single field. FromRadio isn't just the variant: it has
  // "uint32 id = 1" OUTSIDE the oneof, and protobuf serialises in field-number
  // order. When the radio fills that id - and it does on some firmware
  // paths - the first field of the frame is 1, no branch below matches, and
  // THE WHOLE MESSAGE WAS SILENTLY DISCARDED.
  //
  // Reading only the first field was betting the id would always come zeroed (and a zeroed
  // field is omitted by nanopb). The bet works nearly always, which is the worst
  // kind of bug: it vanishes in testing and appears in use.
  while (pb_proximo_campo(&l, &f, &t))
  {
  // FIELD 2, not 1. FromRadio's field 1 is "id"; the packet is 2.
  // Checked against the official protobuf (meshtastic.protobuf.mesh_pb2).
  // With the wrong number, EVERY packet arrived and was discarded as an unknown
  // field - the counter said "0 packets" with a perfect link.
  if (f == 2 && t == 2) { s_c_pacotes++; pb_leitor_t s; if (pb_sub(&l,&s)) ler_packet(s); }
  else if (f == 3 && t == 2) {           // my_info
    pb_leitor_t s;
    if (pb_sub(&l,&s)) {
      mesh_admin_guardar_my_info(s.p, (size_t)(s.fim - s.p));   // reboot_count, nodedb_count
      int n2, t2;
      while (pb_proximo_campo(&s, &n2, &t2)) {
        if (n2 == 1 && t2 == 0) {
          uint64_t v = 0; pb_varint(&s,&v);
          const uint32_t novo = (uint32_t)v;
          // Only writes when it CHANGES: NVS has finite write cycles and
          // my_info arrives on every introduction.
          if (novo != 0 && novo != s_meu_num) { lembrar_meu_numero(novo); }
          s_meu_num = novo;
        }
        else if (n2 == 8 && t2 == 0) {   // reboot_count: the restart journal compares it with the previous one
          uint64_t v = 0; pb_varint(&s, &v);
          // s_ultimo_quadro_ms is still the PREVIOUS frame's (it only updates after
          // ler_from_radio): zero = first contact this session.
          mesh_diario_contador((uint32_t)v, s_saude.uptime_s, s_ultimo_quadro_ms != 0, mesh_admin_gravando());
        }
        else if (!pb_pular(&s, t2)) { break; }
      }
    }
  }
  else if (f == 4 && t == 2) { s_c_nodeinfo++; pb_leitor_t s; if (pb_sub(&l,&s)) ler_node_info(s); }
  else if (f == 11 && t == 2) {          // queueStatus: 1=res 4=mesh_packet_id
    // IMMEDIATE failure, before the packet leaves through the radio: the transmit queue
    // didn't accept it. Without this the send would stay "sending" until the timeout ran out,
    // when the radio had already said it didn't even try.
    pb_leitor_t s;
    if (pb_sub(&l,&s)) {
      int32_t res = 0; uint32_t pid = 0;
      int n2, t2;
      while (pb_proximo_campo(&s, &n2, &t2)) {
        if      (n2 == 1 && t2 == 0) { uint64_t v = 0; pb_varint(&s,&v); res = (int32_t)v; }
        // mesh_packet_id is UINT32 (varint), not fixed32 - checked in
        // mesh.pb.h. Read as fixed32 it never matched, and the
        // radio queue's refusal never marked the send as failed.
        else if (n2 == 4 && t2 == 0) { uint64_t v = 0; pb_varint(&s, &v); pid = (uint32_t)v; }
        else if (!pb_pular(&s, t2)) { break; }
      }
      if (pid != 0 && res != 0) { marcar_envio(pid, MESH_ERRO_FILA, s_meu_num); }
    }
  }
  else if (f == 7 && t == 0) {           // configCompleteId
    // END OF THE CONFIGURATION DOWNLOAD. From here on the radio starts
    // delivering LIVE traffic - before that it is draining the configuration
    // queue. There is nothing to do beyond logging it, but logging it
    // matters: without this line in the log you can't tell "the dump never
    // finished" from "it finished and no messages arrive", and the fix differs.
    uint64_t v = 0;
    if (pb_varint(&l, &v)) {
      s_config_ok_ms = tab5_agora_ms();   // live time counts from here (see marcar_hora_viva)
      // The channel configuration arrived complete: s_canais_sujos is already
      // set, and the "cartao" (SD card) task's piggyback writes within 1 s (off the radio).
      mesh_admin_fim_dump();         // the node's configuration too
      enviar_favs_pendentes();       // stars changed without the radio
      ESP_LOGI(TAG, "configuration complete (id %lu) - live traffic from here",
               (unsigned long)v);
    }
  }
  else if (f == 8 && t == 0) {           // rebooted
    uint64_t v = 0;
    if (pb_varint(&l, &v) && v != 0) {
      // BUS VOLTAGE AT THE MOMENT OF THE RESTART
      // ("is there a way to tell whether the Grove's 5V is getting through?"). We don't measure the
      // Grove specifically (there is only the INA226 on the BATTERY bus,
      // 2S Li-Po ~7.4V - see tab5_power.hpp), and it can't be measured right now
      // either (only tab5_power_ultima(), never _medir() from here: this is the
      // Mesh task, not the UI one, and the internal I2C bus has no
      // mutex - see the big notice in tab5_power.hpp). What "ultima" (latest)
      // returns is a cached reading from UP TO 1s ago, updated by the
      // UI - coarse resolution for a fast voltage dip, but if the bus is
      // visibly low right at the moment of the
      // restart, it is real evidence of a power problem, not just a suspicion.
      mesh_diario_foto(s_saude.uptime_s);   // the Tab5's context at this moment
      const tab5_medida_t m = tab5_power_ultima();
      ESP_LOGW(TAG, "the radio restarted - will request the configuration again "
                    "(bus at that moment: %.2fV %.0fmA, up to 1s ago)",
               (double)m.volts, (double)m.mA);
      s_radio_reiniciou = true;
    }
  }
  // CONFIG AND MODULECONFIG - only what internet mode needs: the region
  // (Config.lora.region, which goes at the root of the topic) and the node's MQTT server
  // (ModuleConfig.mqtt: 2=address 3=username 4=password 8=root). Empty address
  // = the public server, which is the firmware default.
  else if (f == 5 && t == 2) {           // config: oneof 1..10 = section; 6=lora { 7=region }
    pb_leitor_t s, sec;
    int n2, t2;
    if (pb_sub(&l, &s)) {
      while (pb_proximo_campo(&s, &n2, &t2)) {
        if (t2 != 2) { if (!pb_pular(&s, t2)) { break; } continue; }
        if (!pb_sub(&s, &sec)) { break; }
        // The RAW SECTION goes to the node configuration (tab5_mesh_admin): it is what
        // goes back, whole, when a field is changed.
        mesh_admin_guardar_secao(false, n2, sec.p, (size_t)(sec.fim - sec.p));
        if (n2 != 6) { continue; }
        int n3, t3;
        while (pb_proximo_campo(&sec, &n3, &t3)) {
          if (n3 == 7 && t3 == 0) { uint64_t v = 0; pb_varint(&sec, &v); mesh_mqtt_aprender_regiao((int)v); }
          else if (!pb_pular(&sec, t3)) { break; }
        }
      }
    }
  }
  else if (f == 9 && t == 2) {           // moduleConfig: oneof 1..17 = module; 1=mqtt
    pb_leitor_t s, sec;
    int n2, t2;
    if (pb_sub(&l, &s)) {
      while (pb_proximo_campo(&s, &n2, &t2)) {
        if (t2 != 2) { if (!pb_pular(&s, t2)) { break; } continue; }
        if (!pb_sub(&s, &sec)) { break; }
        mesh_admin_guardar_secao(true, n2, sec.p, (size_t)(sec.fim - sec.p));
        if (n2 != 1) { continue; }
        char end[64] = "", usr[32] = "", pwd[32] = "", raiz[48] = "";
        bool mqtt_lig = false, tls = false, proxy = false;   // proto3: absent = false
        int n3, t3;
        while (pb_proximo_campo(&sec, &n3, &t3)) {
          if      (n3 == 1 && t3 == 0) { uint64_t v = 0; pb_varint(&sec, &v); mqtt_lig = (v != 0); }
          else if (n3 == 7 && t3 == 0) { uint64_t v = 0; pb_varint(&sec, &v); tls = (v != 0); }
          else if (n3 == 9 && t3 == 0) { uint64_t v = 0; pb_varint(&sec, &v); proxy = (v != 0); }
          else if (n3 == 2 && t3 == 2) { pb_texto(&sec, end,  sizeof(end)); }
          else if (n3 == 3 && t3 == 2) { pb_texto(&sec, usr,  sizeof(usr)); }
          else if (n3 == 4 && t3 == 2) { pb_texto(&sec, pwd,  sizeof(pwd)); }
          else if (n3 == 8 && t3 == 2) { pb_texto(&sec, raiz, sizeof(raiz)); }
          else if (!pb_pular(&sec, t3)) { break; }
        }
        mesh_mqtt_aprender_servidor(end, usr, pwd, raiz);
        mesh_mqtt_aprender_no_mqtt(mqtt_lig, proxy, tls);
      }
    }
  }
  else if (f == 10 && t == 2) {          // channel: 1=index 2=settings 3=role
    pb_leitor_t s;
    if (pb_sub(&l,&s)) {
      const uint8_t* ch_ini = s.p;
      const size_t   ch_n = (size_t)(s.fim - s.p);
      // BOTH START AT ZERO, and that is the fix for two bugs.
      //
      // 'index' (int32) and 'role' (enum) are SINGULAR proto3 fields: nanopb
      // does NOT write them when they are zero. Starting at -1 and 1, as it was:
      //   - channel 0 (the primary, LongFast) arrived WITHOUT field 1, ended up with
      //     idx -1 and its whole configuration was ignored - it never got in
      //     as active, and so didn't appear to reopen after being deleted;
      //   - a DISABLED channel (role 0) arrived WITHOUT field 3 and was read as
      //     PRIMARY - it stayed "active", with its old name, in the column.
      // The absent value is protobuf's zero: that is what the firmware meant.
      int idx = 0, papel = 0;
      bool downlink = false, uplink = false;
      char nome[MESH_NOME_CONVERSA] = { 0 };
      uint8_t psk[32];
      size_t  n_psk = 0;
      int n2, t2;
      while (pb_proximo_campo(&s, &n2, &t2)) {
        if      (n2 == 1 && t2 == 0) { uint64_t v = 0; pb_varint(&s,&v); idx = (int)v; }
        else if (n2 == 3 && t2 == 0) { uint64_t v = 0; pb_varint(&s,&v); papel = (int)v; }
        else if (n2 == 2 && t2 == 2) {           // ChannelSettings: 2=psk 3=name
          pb_leitor_t cs;
          if (pb_sub(&s,&cs)) {
            int n3, t3;
            while (pb_proximo_campo(&cs, &n3, &t3)) {
              if (n3 == 3 && t3 == 2) { pb_texto(&cs, nome, sizeof(nome)); }
              else if (n3 == 6 && t3 == 0) { uint64_t v = 0; pb_varint(&cs, &v); downlink = (v != 0); }   // the proxy subscribes
              else if (n3 == 5 && t3 == 0) { uint64_t v = 0; pb_varint(&cs, &v); uplink = (v != 0); }     // only for diagnostics
              else if (n3 == 2 && t3 == 2) {   // psk: the key, for internet mode
                uint64_t k;
                if (!pb_varint(&cs, &k) || k > pb_restam(&cs)) { break; }
                n_psk = (k <= sizeof(psk)) ? (size_t)k : 0;
                if (n_psk) { memcpy(psk, cs.p, n_psk); }
                cs.p += (size_t)k;
              }
              else if (!pb_pular(&cs, t3)) { break; }
            }
          }
        }
        else if (!pb_pular(&s, t2)) { break; }
      }
      // The RAW Channel goes to the node configuration (the primary's position precision
      // is edited there, and comes back with the rest of it intact).
      mesh_admin_guardar_canal(idx, ch_ini, ch_n);
      if (idx >= 0 && idx < MESH_MAX_CANAIS) {
        mesh_mqtt_aprender_downlink(idx, papel != 0 && downlink);   // before: aplicar_canal teaches the name
        mesh_mqtt_aprender_uplink(idx, papel != 0 && uplink);
        aplicar_canal(idx, papel, nome, psk, n_psk);
      }
    }
  }
  else if (f == 14 && t == 2) {          // mqttClientProxyMessage: 1=topic 2=data 3=text 4=retained
    // THE NODE ASKING TO PUBLISH (proxy enabled on it). Without the proxy on the
    // Tab5 side the message is just discarded - the node doesn't wait for a reply.
    pb_leitor_t s;
    if (pb_sub(&l, &s)) {
      static char topico[128];   // only the service task reads FromRadio
      topico[0] = 0;
      const uint8_t* dado = nullptr; size_t n_dado = 0;
      bool retido = false;
      int n2, t2;
      while (pb_proximo_campo(&s, &n2, &t2)) {
        if (n2 == 1 && t2 == 2) { pb_texto(&s, topico, sizeof(topico)); }
        else if ((n2 == 2 || n2 == 3) && t2 == 2) {   // data (bytes) or text: both go raw
          uint64_t k;
          if (!pb_varint(&s, &k) || k > pb_restam(&s)) { break; }
          dado = s.p; n_dado = (size_t)k; s.p += (size_t)k;
        }
        else if (n2 == 4 && t2 == 0) { uint64_t v = 0; pb_varint(&s, &v); retido = (v != 0); }
        else if (!pb_pular(&s, t2)) { break; }
      }
      if (mesh_mqtt_em_proxy() && topico[0] && dado) { mesh_mqtt_proxy_publicar(topico, dado, n_dado, retido); }
    }
  }
  else if (f == 16 && t == 2) {          // clientNotification: firmware notice for the user
    pb_leitor_t s;
    if (pb_sub(&l, &s)) { mesh_admin_guardar_aviso(s.p, (size_t)(s.fim - s.p)); }
  }
  else if (f == 13 && t == 2) {          // metadata: 1=firmware_version
    pb_leitor_t s;
    if (pb_sub(&l,&s)) {
      mesh_admin_guardar_metadata(s.p, (size_t)(s.fim - s.p));
      int n2, t2;
      while (pb_proximo_campo(&s, &n2, &t2)) {
        if (n2 == 1 && t2 == 2) { pb_texto(&s, s_firmware, sizeof(s_firmware)); }
        else if (!pb_pular(&s, t2)) { break; }
      }
    }
  }
  // config and the rest: skipped, so the loop reaches the next field instead of
  // stopping at the first unknown one.
  else if (!pb_pular(&l, t)) { break; }
  }
}
